test('preserva deck ao criar sala, acompanhar participação e recarregar', async ({ page, browser, baseURL }, testInfo) => {
  const activate = async (button: Locator) => testInfo.project.use.hasTouch ? button.tap() : button.click();
  await page.goto('/');
  await page.getByLabel('Login', { exact: true }).fill('amigo');
  await page.getByLabel('Senha', { exact: true }).fill('senha-do-navegador');
  await page.getByRole('button', { name: 'Entrar', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Salas', exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Meus decks', exact: true }).click();
  await page.getByLabel('Arquivo .cod').setInputFiles({ name: 'amigos.cod', mimeType: 'application/xml', buffer: readFileSync(resolve('../api/tests/integration/testdata/cockatrice-deck.cod')) });
  await page.getByRole('button', { name: 'Importar deck', exact: true }).click();
  await expect(page.getByText('5 × Island', { exact: true })).toBeVisible();
  const uploadedDeckId = await page.getByLabel('Escolher deck salvo').inputValue();
  await page.getByRole('link', { name: 'Salas', exact: true }).click();
  const rooms = page.getByRole('region', { name: 'Salas', exact: true });
  const viewer = await browser.newContext({ baseURL, viewport: testInfo.project.use.viewport, isMobile: testInfo.project.use.isMobile, hasTouch: testInfo.project.use.hasTouch });
  try {
    const other = await viewer.newPage();
    await other.goto('/');
    await other.getByLabel('Login', { exact: true }).fill('segundo');
    await other.getByLabel('Senha', { exact: true }).fill('senha-do-navegador');
    await other.getByRole('button', { name: 'Entrar', exact: true }).click();
    await expect(other.getByRole('heading', { name: 'Salas', exact: true })).toBeVisible();
    const before = await rooms.getByRole('article').count();
    const knownTitles = new Set(await rooms.getByRole('article').locator('h3').allTextContents());
    await activate(page.getByRole('button', { name: 'Criar sala', exact: true }));
    const createPanel = page.getByRole('dialog', { name: 'Montar a mesa' });
    await createPanel.getByLabel('Nome da mesa').fill('Mesa das salas');
    await createPanel.getByLabel('Lugares').fill('6');
    await createPanel.getByRole('button', { name: 'Criar e sentar' }).click();
    await expect(page).toHaveURL(/#\/salas\/\d+$/);
    await expect(page.getByRole('region', { name: 'Preparação da sala' })).toBeVisible();
    await page.getByRole('link', { name: 'Voltar ao lobby' }).click();
    await expect(rooms.getByRole('article')).toHaveCount(before + 1);
    const title = (await rooms.getByRole('article').locator('h3').allTextContents()).find(value => !knownTitles.has(value))!;
    const mine = rooms.getByRole('article').filter({ has: page.getByRole('heading', { name: title, exact: true }) });
    const theirs = other.getByRole('article').filter({ has: other.getByRole('heading', { name: title, exact: true }) });
    await expect(theirs.getByText('5 vagas', { exact: true })).toBeVisible();
    await activate(theirs.getByRole('button', { name: 'Entrar na sala', exact: true }));
    await expect(other).toHaveURL(/#\/salas\/\d+$/);
    await expect(other.getByRole('region', { name: 'Preparação da sala' })).toBeVisible();
    await other.getByRole('link', { name: 'Voltar ao lobby' }).click();
    await expect(mine.getByText('Segundo amigo')).toBeVisible();
    await expect(mine.getByText('4 vagas', { exact: true })).toBeVisible();
    await expect(theirs.getByRole('link', { name: 'Entrar na mesa', exact: true })).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: testInfo.outputPath('salas.png'), fullPage: true });
    await page.reload();
    await expect(rooms.getByRole('article').filter({ has: page.getByRole('heading', { name: title, exact: true }) }).getByRole('link', { name: 'Entrar na mesa', exact: true })).toBeVisible();
    await page.getByRole('link', { name: 'Meus decks', exact: true }).click();
    await page.getByLabel('Escolher deck salvo').selectOption(uploadedDeckId);
    await expect(page.getByText('5 × Island', { exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'Excluir deck', exact: true }).click();
    await page.getByRole('dialog', { name: 'Excluir deck?' }).getByRole('button', { name: 'Confirmar exclusão' }).click();
    await expect(page.getByLabel('Escolher deck salvo').locator(`option[value="${uploadedDeckId}"]`)).toHaveCount(0);
    await page.getByRole('button', { name: 'Sair', exact: true }).click();
    await expect(page.getByLabel('Login', { exact: true })).toBeVisible();
  } finally { await viewer.close(); }
});

test('entra na URL da mesa, move por todas as zonas e recupera após erro e recarga', async ({ page }, testInfo) => {
  test.setTimeout(60_000);
  const activate = async (button: Locator) => testInfo.project.use.hasTouch ? button.tap() : button.click();
  await page.goto('/');
  await page.getByLabel('Login', { exact: true }).fill('amigo');
  await page.getByLabel('Senha', { exact: true }).fill('senha-do-navegador');
  await page.getByRole('button', { name: 'Entrar', exact: true }).click();
  await page.getByRole('link', { name: 'Meus decks', exact: true }).click();
  await page.getByLabel('Arquivo .cod').setInputFiles({ name: 'movimentos.cod', mimeType: 'application/xml', buffer: Buffer.from('<cockatrice_deck version="1"><deckname>Movimentos</deckname><zone name="main"><card number="5" name="Island"/></zone></cockatrice_deck>') });
  await page.getByRole('button', { name: 'Importar deck', exact: true }).click();
  await page.getByRole('link', { name: 'Salas', exact: true }).click();
  await expect(page.getByText('Salas atualizadas em tempo real.', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Criar sala', exact: true }).click();
  const createPanel = page.getByRole('dialog', { name: 'Montar a mesa' });
  await createPanel.getByLabel('Nome da mesa').fill('Mesa dos movimentos');
  await createPanel.getByRole('button', { name: 'Criar e sentar' }).click();
  await expect(page).toHaveURL(/#\/salas\/\d+$/);
  await choosePreparationDeck(page, { label: 'Movimentos' });
  await page.getByRole('button', { name: 'Estou pronto', exact: true }).click();
  const mobilePreparation = await page.locator('.mobile-preparation').isVisible();
  await expect(page.getByRole('button', { name: mobilePreparation ? 'desfazer pronto' : 'Desfazer prontidão', exact: true })).toBeVisible();
  await expect(page.getByRole('listitem').filter({ hasText: 'Amigo da mesa' }).filter({ hasText: 'Pronto' }).first()).toBeVisible();
  await page.getByRole('button', { name: 'Iniciar partida', exact: true }).click();
  const board = page.getByRole('region', { name: 'Mesa da partida', exact: true });
  await expect(board).toBeVisible();
  const roomURL = page.url();
  const matchPath = `/api/rooms/${roomURL.split('/').at(-1)}/match`;
  await returnOpeningHandToLibrary(page.request, Number(roomURL.split('/').at(-1)));
  const ownHand = async (): Promise<{ id: string }[]> => {
    const response = await page.request.get(matchPath);
    expect(response.ok()).toBe(true);
    const { match } = await response.json();
    return match.players.find((player: { userId: number }) => player.userId === match.viewerId).hand || [];
  };
  if (testInfo.project.name === 'celular') {
    await openQuickActions(page);
    await expect(board.getByRole('button', { name: 'Comprar', exact: true })).toBeVisible();
    await closeQuickActions(page);
  }
  await expect(board.getByLabel('Vida: 40', { exact: true })).toBeVisible();
  await expect(board.getByLabel('Zonas de Amigo da mesa')).toContainText('Grimório');
  await expect(board.getByLabel('Zonas de Amigo da mesa')).toContainText('Campo');
  const hand = board.getByRole('region', { name: 'Mão', exact: true });
  const buy = async (amount: string) => {
    await closeMatchRail(page);
    const library = await openLibrary(page);
    const quantity = library.getByLabel('Quantidade de cartas');
    if (!(await quantity.isVisible())) {
      await activate(board.getByRole('button', { name: 'Comprar cartas', exact: true }));
    }
    await quantity.fill(amount);
    await activate(library.getByRole('button', { name: /^Comprar \d+ carta/ }));
  };
  const closeActions = async () => {
    const close = board.getByRole('button', { name: 'Fechar painel do grimório', exact: true });
    if (await close.isVisible()) await activate(close);
  };
  const library = await openLibrary(page);
  await library.getByRole('button', { name: 'Comprar cartas', exact: true }).click();
  await library.getByLabel('Quantidade de cartas').fill('1000');
  await expect(library.getByRole('button', { name: 'Comprar 1000 cartas', exact: true })).toBeDisabled();
  expect(await ownHand()).toHaveLength(0);
  await library.getByLabel('Quantidade de cartas').fill('1');
  let lostResponses = 0;
  await page.route('**/match/actions', async route => {
    if (lostResponses < 2) {
      lostResponses += 1;
      const persisted = await route.fetch();
      expect(persisted.status()).toBe(200);
      await route.abort('failed');
    } else await route.continue();
  });
  await activate(library.getByRole('button', { name: 'Comprar 1 carta', exact: true }));
  await expect(library.getByRole('alert')).toContainText('Não foi possível confirmar');
  await expect(library.getByRole('button', { name: 'Comprar 1 carta', exact: true })).toBeDisabled();
  await activate(library.getByRole('button', { name: 'Tentar novamente', exact: true }));
  await page.unroute('**/match/actions');
  await expect(board.getByRole('alert')).toHaveCount(0);
  expect(await ownHand()).toHaveLength(1);
  const confirmed = await (await page.request.get(matchPath)).json();
  expect(confirmed.match.log.filter((entry: { kind: string }) => entry.kind === 'draw')).toHaveLength(1);
  await closeActions();
  await openHand(page);
  await expect(hand.getByRole('button', { name: 'Island', exact: true })).toBeVisible();
  async function dragCard(from: Locator, to: Locator) {
    await from.evaluate(element => element.scrollIntoView({ block: 'center', inline: 'nearest' }));
    const sourceBox = await from.boundingBox();
    expect(sourceBox, 'carta de origem visível').toBeTruthy();
    await page.mouse.move(sourceBox!.x + sourceBox!.width / 2, sourceBox!.y + sourceBox!.height / 2);
    await page.mouse.down();
    if (await to.count() === 0) await page.mouse.move(sourceBox!.x + sourceBox!.width / 2, sourceBox!.y + sourceBox!.height / 2 - 16, { steps: 4 });
    await to.evaluate(element => element.scrollIntoView({ block: 'center', inline: 'nearest' }));
    const targetBox = await to.boundingBox();
    expect(targetBox, 'zona de destino visível').toBeTruthy();
    await page.mouse.move(targetBox!.x + targetBox!.width / 2, targetBox!.y + targetBox!.height / 2, { steps: 12 });
    await page.mouse.up();
  }
  let source = hand;
  for (const destination of ['Campo', 'Cemitério', 'Exílio', 'Comando', 'Mão']) {
    if (destination === 'Mão') await openHand(page);
    else if (destination !== 'Campo') await closeHand(page);
    const target = board.getByRole('region', { name: destination, exact: true });
    await dragCard(source.getByRole('button', { name: 'Island', exact: true }), target);
    await expect(target.getByRole('button', { name: 'Island', exact: true })).toBeVisible();
    await expect(source.getByRole('button', { name: 'Island', exact: true })).toHaveCount(0);
    source = target;
  }
  const returnedId = (await ownHand())[0].id;
  await dragCard(hand.getByRole('button', { name: 'Island', exact: true }), board.getByRole('button', { name: 'Abrir ações do grimório' }));
  await expect(hand.locator('.playing-card')).toHaveCount(0);
  await buy('1');
  await closeActions();
  await expect(hand.locator('.playing-card')).toHaveCount(1);
  expect((await ownHand())[0].id).toBe(returnedId);
  await hand.getByRole('button', { name: 'Island', exact: true }).click();
  await page.getByRole('dialog', { name: 'Imagem de Island', exact: true }).getByRole('button', { name: 'Fundo', exact: true }).click();
  await expect(hand.locator('.playing-card')).toHaveCount(0);
  await buy('1');
  await closeActions();
  await expect(hand.locator('.playing-card')).toHaveCount(1);
  expect((await ownHand())[0].id).not.toBe(returnedId);
  await dragCard(hand.getByRole('button', { name: 'Island', exact: true }), board.getByRole('region', { name: 'Campo', exact: true }));
  await expect(board.getByRole('region', { name: 'Campo', exact: true }).getByRole('button', { name: 'Island' })).toBeVisible();
  await page.reload();
  await expect(page).toHaveURL(roomURL);
  await expect(board.getByRole('region', { name: 'Campo', exact: true }).getByRole('button', { name: 'Island' })).toBeVisible();
  await openMatchRail(page, 'Registro');
  await expect(board.getByRole('region', { name: 'Registro da partida', exact: true }).getByText('Amigo da mesa moveu 1 carta(s) de Mão para Grimório.')).toHaveCount(2);
  await page.getByRole('link', { name: 'Voltar ao lobby' }).click();
  await expect(board).toHaveCount(0);
  await page.goto(roomURL);
  await openMatchRail(page, 'Registro');
  await expect(board.getByRole('region', { name: 'Campo', exact: true }).getByRole('button', { name: 'Island' })).toBeVisible();
  await openHand(page);
  await buy('3');
  await expect(hand.locator('.playing-card')).toHaveCount(3);
  expect((await ownHand()).map(card => card.id)).not.toContain(returnedId);
  await buy('1');
  await expect(hand.locator('.playing-card')).toHaveCount(4);
  expect((await ownHand()).at(-1)?.id).toBe(returnedId);
  const log = board.getByRole('region', { name: 'Registro da partida', exact: true });
  await closeActions();
  const actions = board.getByRole('dialog', { name: 'Ações do jogo', exact: true });
  const openActions = async () => {
    if (await actions.isVisible()) return;
    await openQuickActions(page);
    await activate(board.getByRole('button', { name: 'Ações', exact: true }));
    await expect(actions).toBeVisible();
  };
  await openActions();
  await activate(board.getByRole('button', { name: 'Rolar dado', exact: true }));
  await board.getByLabel('Faces do dado').fill('6');
  await activate(board.getByRole('button', { name: /^Rolar d\d+$/ }));
  await activate(actions.getByRole('button', { name: 'Cancelar', exact: true }));
  const showLog = async () => {
    if (await actions.isVisible()) await activate(actions.getByRole('button', { name: 'Fechar ações', exact: true }));
    await openMatchRail(page, 'Registro');
  };
  await showLog();
  await expect(log).toContainText(/Amigo da mesa rolou D6: /);
  await closeMatchRail(page);
  await openActions();
  await activate(board.getByRole('button', { name: 'Jogar moeda', exact: true }));
  await activate(actions.getByRole('button', { name: 'Jogar moeda', exact: true }));
  await showLog();
  await expect(log).toContainText(/Amigo da mesa jogou uma moeda: (Cara|Coroa)\./);
  await closeMatchRail(page);
  await openQuickActions(page);
  await activate(board.getByRole('button', { name: 'Passar turno', exact: true }));
  await showLog();
  await expect(log).toContainText('Amigo da mesa avançou para o turno de Amigo da mesa e ocultou todas as revelações.');
  await closeMatchRail(page);
  await openQuickActions(page);
  await activate(board.getByRole('button', { name: 'Corrigir turno', exact: true }));
  await showLog();
  await expect(log).toContainText('Amigo da mesa corrigiu para o turno de Amigo da mesa.');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('mesa.png'), fullPage: true });
});

test('navega entre lobby e biblioteca com teclado, histórico e recarga', async ({ page }) => {
  await page.goto('/');
  await page.getByLabel('Login', { exact: true }).fill('amigo');
  await page.getByLabel('Senha', { exact: true }).fill('senha-do-navegador');
  await page.getByRole('button', { name: 'Entrar', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Lobby' })).toBeVisible();
  const decksLink = page.getByRole('link', { name: 'Meus decks', exact: true });
  await decksLink.focus();
  await page.keyboard.press('Enter');
  await expect(page).toHaveURL(/#\/decks$/);
  await expect(page.getByRole('heading', { name: 'Seus decks, em um só lugar.' })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Meus decks', exact: true })).toBeVisible();
  await page.goBack();
  await expect(page.getByRole('heading', { name: 'Lobby' })).toBeVisible();
});
