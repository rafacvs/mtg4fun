import { randomUUID } from 'node:crypto';
import { test, expect, openHand } from './fixtures';

test('selo distingue o impresso da ficha do modificador manual', async ({ page }) => {
  const api = page.request;
  expect((await api.post('/api/session', { data: { login: 'amigo', password: 'senha-do-navegador' } })).ok()).toBe(true);
  const { deck } = await (await api.post('/api/decks', { multipart: { file: { name: 'stats.cod', mimeType: 'application/xml', buffer: Buffer.from('<cockatrice_deck><zone name="main"><card number="1" name="Island"/></zone></cockatrice_deck>') } } })).json();
  const { room } = await (await api.post('/api/rooms', { data: {} })).json();
  const path = `/api/rooms/${room.id}`;
  expect((await api.put(`${path}/participants/me/ready`, { data: { deckId: deck.id } })).ok()).toBe(true);
  expect((await api.post(`${path}/start`, { data: {} })).status()).toBe(201);
  const result = await api.post(`${path}/match/actions`, { data: { intentId: randomUUID(), kind: 'create-token', tokenName: 'Soldier Token' } });
  expect(result.ok()).toBe(true);
  const { match } = await result.json();
  const id = match.players[0].battlefield[0].id;
  await page.goto(`/#/salas/${room.id}`);
  const card = page.locator('.playing-card[aria-label="Soldier Token"]');
  const badge = card.getByLabel('Poder e resistência');
  await expect(badge).toHaveText('1/1');
  await expect(badge).toHaveAttribute('data-modified', 'false');
  const unmodifiedColor = await badge.evaluate(node => getComputedStyle(node).backgroundColor);
  expect((await api.post(`${path}/match/actions`, { data: { intentId: randomUUID(), kind: 'counter', target: 'card', cardId: id, subject: 'power', operation: 'increment', value: 2 } })).ok()).toBe(true);
  await expect(badge).toHaveText('3/1');
  await expect(badge).toHaveAttribute('data-modified', 'true');
  await expect.poll(() => badge.evaluate(node => getComputedStyle(node).backgroundColor)).not.toBe(unmodifiedColor);
  await page.reload();
  await expect(badge).toHaveText('3/1');
  const symbolic = await api.post(`${path}/match/actions`, { data: { intentId: randomUUID(), kind: 'create-token', tokenName: 'Symbolic Token' } });
  expect(symbolic.ok()).toBe(true);
  const symbolicState = await symbolic.json();
  const symbolicId = symbolicState.match.players[0].battlefield.find((item: { name: string }) => item.name === 'Symbolic Token').id;
  const symbolicBadge = page.locator('.playing-card[aria-label="Symbolic Token"]').getByLabel('Poder e resistência');
  await expect(symbolicBadge).toHaveText('*/1+*');
  expect((await api.post(`${path}/match/actions`, { data: { intentId: randomUUID(), kind: 'counter', target: 'card', cardId: symbolicId, subject: 'toughness', operation: 'increment', value: -2 } })).ok()).toBe(true);
  await expect(symbolicBadge).toHaveText('*/1+* (+0/-2)');
  expect((await api.post(`${path}/match/actions`, { data: { intentId: randomUUID(), kind: 'draw', count: 1 } })).ok()).toBe(true);
  await openHand(page);
  await expect(page.locator('.playing-card[aria-label="Island"]')).toBeVisible();
  await expect(page.locator('.playing-card[aria-label="Island"]').getByLabel('Poder e resistência')).toHaveCount(0);
});
