import { test, expect, roomBody } from './fixtures';

for (const viewport of [{ width: 1312, height: 825 }, { width: 1100, height: 700 }, { width: 390, height: 844 }, { width: 844, height: 390 }]) test(`submenus de ações em ${viewport.width}x${viewport.height}`, async ({ page }, testInfo) => {
  test.skip(testInfo.project.name !== 'desktop'); test.setTimeout(90_000);
  const api = page.request;
  expect((await api.post('/api/session', { data: { login: 'amigo', password: 'senha-do-navegador' } })).ok()).toBeTruthy();
  const { deck } = await (await api.post('/api/decks', { multipart: { file: { name: 'deck.cod', mimeType: 'application/xml', buffer: Buffer.from('<cockatrice_deck><zone name="main"><card number="8" name="Island"/></zone></cockatrice_deck>') } } })).json();
  const { room } = await (await api.post('/api/rooms', { data: roomBody() })).json();
  await api.put(`/api/rooms/${room.id}/participants/me/ready`, { data: { deckId: deck.id } });
  expect((await api.post(`/api/rooms/${room.id}/start`, { data: {} })).ok()).toBeTruthy();
  await page.setViewportSize(viewport); await page.goto(`/#/salas/${room.id}`);
  if (viewport.width <= 1000) await page.getByRole('button', { name: 'Comandos', exact: true }).click();
  await page.getByRole('navigation', { name: 'Ações rápidas' }).getByRole('button', { name: 'Ações', exact: true }).click();
  const panel = page.getByRole('dialog', { name: 'Ações do jogo' });
  const size = await panel.boundingBox();
  const sameSize = async () => { const next = await panel.boundingBox(); expect(next!.width).toBeCloseTo(size!.width, 0); expect(next!.height).toBeCloseTo(size!.height, 0); const footer = await panel.locator(".game-submenu-buttons").boundingBox(); expect(footer!.y + footer!.height).toBeLessThanOrEqual(next!.y + next!.height + 1); };
  await panel.getByRole('button', { name: 'Rolar dado', exact: true }).click(); await sameSize();
  await page.screenshot({ path: testInfo.outputPath('dado.png'), animations: 'disabled' });
  await panel.getByLabel('Faces do dado').fill('12'); await panel.getByRole('button', { name: 'Rolar d12' }).click();
  await expect.poll(async () => (await (await api.get(`/api/rooms/${room.id}/match`)).json()).match.log.some((item: { kind: string }) => item.kind === 'roll')).toBe(true);
  await panel.getByRole('button', { name: 'Cancelar' }).click();
  await panel.getByRole('button', { name: 'Jogar moeda', exact: true }).click(); await sameSize();
  await panel.getByRole('button', { name: 'Coroa', exact: true }).click(); await expect(panel.getByText('Você escolheu Coroa.')).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('moeda.png'), animations: 'disabled' });
  await panel.getByRole('button', { name: 'Jogar moeda', exact: true }).click();
  await expect.poll(async () => (await (await api.get(`/api/rooms/${room.id}/match`)).json()).match.log.some((item: { kind: string }) => item.kind === 'coin')).toBe(true);
  await panel.getByRole('button', { name: 'Cancelar' }).click();
  await panel.getByRole('button', { name: 'Criar ficha', exact: true }).click(); await sameSize();
  await panel.getByRole('button', { name: 'Selecionar Soldier Token' }).click();
  await page.screenshot({ path: testInfo.outputPath('catalogo.png'), animations: 'disabled' });
  await panel.getByRole('button', { name: 'Criar ficha', exact: true }).click();
  await expect.poll(async () => (await (await api.get(`/api/rooms/${room.id}/match`)).json()).match.players[0].battlefield?.some((card: { name: string }) => card.name === 'Soldier Token')).toBe(true);
  await panel.getByRole('tab', { name: 'Personalizada' }).click(); await sameSize();
  const previewBox = await panel.locator('.custom-token-card').boundingBox();
  expect(previewBox!.width / previewBox!.height).toBeCloseTo(63 / 88, 2);
  const description = 'Uma descrição longa que continua em várias linhas e precisa permanecer legível na prévia. '.repeat(6) + 'Fim da descrição.';
  await panel.getByLabel('Nome da ficha').fill('Espírito'); await panel.getByLabel('Descrição da ficha').fill(description);
  const previewText = panel.getByLabel('Descrição na prévia');
  await expect(previewText).toHaveText(description);
  expect(await previewText.evaluate(node => node.scrollHeight > node.clientHeight)).toBe(true);
  await previewText.evaluate(node => { node.scrollTop = node.scrollHeight; });
  expect(await previewText.evaluate(node => node.scrollTop)).toBeGreaterThan(0);
  await panel.getByLabel('Poder/resistência da ficha').fill('1/2');
  await panel.getByRole('button', { name: 'Aumentar poder e resistência' }).click();
  await expect(panel.getByLabel('Poder/resistência da ficha')).toHaveValue('2/3');
  await panel.getByLabel('Poder/resistência da ficha').fill('2/x');
  await expect(panel.getByRole('button', { name: 'Criar ficha', exact: true })).toBeDisabled();
  await panel.getByLabel('Poder/resistência da ficha').fill('2/3');
  const cardBottom = (await panel.locator('.custom-token-card').boundingBox())!;
  const statsBottom = (await panel.locator('.custom-token-stats').boundingBox())!;
  expect(Math.abs(cardBottom.y + cardBottom.height - statsBottom.y - statsBottom.height)).toBeLessThanOrEqual(2);
  await page.screenshot({ path: testInfo.outputPath('personalizada.png'), animations: 'disabled' });
  await panel.getByRole('button', { name: 'Criar ficha', exact: true }).click();
  await expect.poll(async () => (await (await api.get(`/api/rooms/${room.id}/match`)).json()).match.players[0].battlefield?.some((card: { name: string }) => card.name === 'Espírito')).toBe(true);
});
